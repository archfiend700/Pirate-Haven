CAPTION = "Ole Jolly Roger"


def show(tool_name: str, tagline: str) -> None:
    """Print the flag banner with a tool name and tagline underneath."""
    print(FLAG.rstrip("\n"))
    width = 60
    print(f"{CAPTION:^{width}}")
    print(f"{'☠ ' + tool_name + ' ☠':^{width}}")
    print(f"{tagline:^{width}}")
    print("-" * width)
